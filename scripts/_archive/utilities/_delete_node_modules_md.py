#!/usr/bin/env python3
"""安全刪除 node_modules 內的 MD 檔案"""
import os
from pathlib import Path
from datetime import datetime

def find_node_modules_md_files():
    """找出所有 node_modules 內的 MD 檔案"""
    services_path = Path('services')
    node_modules_md = []
    
    # 掃描 services/scan/engines/*/node_modules/**/*.md
    for engine_dir in services_path.glob('scan/engines/*'):
        if engine_dir.is_dir():
            node_modules_path = engine_dir / 'node_modules'
            if node_modules_path.exists():
                md_files = list(node_modules_path.rglob('*.md'))
                node_modules_md.extend(md_files)
    
    return node_modules_md

def create_backup_list(files):
    """建立備份清單"""
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    backup_file = f'_deleted_files_backup_{timestamp}.txt'
    
    with open(backup_file, 'w', encoding='utf-8') as f:
        f.write(f"刪除時間: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write(f"總檔案數: {len(files)}\n")
        f.write("=" * 80 + "\n\n")
        
        for file_path in files:
            rel_path = file_path.relative_to('.')
            f.write(f"{rel_path}\n")
            f.write(f"  大小: {file_path.stat().st_size} bytes\n")
            f.write(f"  修改時間: {datetime.fromtimestamp(file_path.stat().st_mtime)}\n")
            f.write("\n")
    
    return backup_file

def delete_files(files, dry_run=True):
    """刪除檔案"""
    print("=" * 80)
    print(f"node_modules MD 檔案刪除工具 ({'預覽模式' if dry_run else '執行模式'})")
    print("=" * 80)
    print()
    
    if not files:
        print("❌ 未找到任何需要刪除的檔案")
        return
    
    print(f"找到 {len(files)} 個 node_modules 內的 MD 檔案")
    print()
    
    # 按引擎分組統計
    by_engine = {}
    for file_path in files:
        parts = file_path.parts
        if 'engines' in parts:
            idx = parts.index('engines')
            if idx + 1 < len(parts):
                engine_name = parts[idx + 1]
                by_engine.setdefault(engine_name, []).append(file_path)
    
    print("檔案分佈:")
    for engine, engine_files in sorted(by_engine.items()):
        total_size = sum(f.stat().st_size for f in engine_files)
        print(f"  📦 {engine}: {len(engine_files)} 個檔案 ({total_size:,} bytes)")
    print()
    
    if not dry_run:
        # 建立備份清單
        backup_file = create_backup_list(files)
        print(f"✅ 已建立備份清單: {backup_file}")
        print()
        
        # 執行刪除
        success_count = 0
        failed_count = 0
        
        print("開始刪除檔案...")
        for file_path in files:
            try:
                file_path.unlink()
                success_count += 1
                if success_count <= 10:
                    print(f"  ✓ {file_path.relative_to('.')}")
            except Exception as e:
                failed_count += 1
                print(f"  ✗ {file_path.relative_to('.')}: {e}")
        
        if success_count > 10:
            print(f"  ... 還成功刪除了 {success_count - 10} 個")
        
        print()
        print("=" * 80)
        print("刪除結果:")
        print("=" * 80)
        print(f"✅ 成功刪除: {success_count} 個")
        if failed_count > 0:
            print(f"❌ 刪除失敗: {failed_count} 個")
        print(f"📋 備份清單: {backup_file}")
        print()
        
        # 計算釋放空間
        total_freed = sum(f.stat().st_size for f in files if not f.exists())
        if total_freed > 0:
            print(f"💾 釋放空間: {total_freed:,} bytes ({total_freed / 1024 / 1024:.2f} MB)")
        print()
    else:
        print("=" * 80)
        print("這是預覽模式，未實際刪除檔案")
        print("要執行實際刪除，請使用參數: --execute")
        print("=" * 80)
        print()
        
        print("預覽前 10 個將被刪除的檔案:")
        for file_path in files[:10]:
            rel_path = file_path.relative_to('.')
            size = file_path.stat().st_size
            print(f"  - {rel_path} ({size} bytes)")
        
        if len(files) > 10:
            print(f"  ... 還有 {len(files) - 10} 個")
        print()
        
        total_size = sum(f.stat().st_size for f in files)
        print(f"總計將釋放: {total_size:,} bytes ({total_size / 1024 / 1024:.2f} MB)")
        print()

def main():
    import sys
    
    print("掃描 node_modules 目錄...")
    files = find_node_modules_md_files()
    print(f"找到 {len(files)} 個檔案\n")
    
    dry_run = '--execute' not in sys.argv
    delete_files(files, dry_run=dry_run)
    
    # 處理 pytest_cache
    pytest_readme = Path('services/core/.pytest_cache/README.md')
    if pytest_readme.exists():
        print()
        print("=" * 80)
        print("其他發現的檔案")
        print("=" * 80)
        print()
        print("📄 services/core/.pytest_cache/README.md")
        print("   這是 pytest 快取目錄的說明文件")
        print("   內容: '不要提交到版本控制'")
        print()
        print("💡 建議:")
        print("   1. 這個檔案可以保留（pytest 自動生成）")
        print("   2. 確保 .pytest_cache/ 已加入 .gitignore")
        print("   3. 如果要刪除，執行: rm services/core/.pytest_cache/README.md")
        print()

if __name__ == '__main__':
    main()
