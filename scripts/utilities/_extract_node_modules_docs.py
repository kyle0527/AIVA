#!/usr/bin/env python3
"""讀取並整合所有簡短 MD 檔案的內容"""
import re
from pathlib import Path
from collections import defaultdict

def extract_md_content():
    """提取所有簡短 MD 檔案的內容並分類"""
    
    node_modules_path = Path('services/scan/engines/typescript_engine/node_modules')
    
    if not node_modules_path.exists():
        print("❌ node_modules 目錄不存在")
        return None
    
    # 收集所有 MD 檔案
    md_files = list(node_modules_path.rglob('*.md'))
    print(f"找到 {len(md_files)} 個 MD 檔案")
    print()
    
    # 分類
    categories = {
        'README': [],
        'LICENSE': [],
        'CHANGELOG': [],
        'HISTORY': [],
        'CONTRIBUTING': [],
        'SECURITY': [],
        'CODE_OF_CONDUCT': [],
        'API_DOC': [],
        'GUIDE': [],
        'OTHER': []
    }
    
    package_info = defaultdict(lambda: {
        'name': '',
        'path': '',
        'readme': None,
        'license': None,
        'changelog': None,
        'other_docs': []
    })
    
    for md_file in md_files:
        try:
            # 讀取內容
            with open(md_file, 'r', encoding='utf-8') as f:
                content = f.read()
            
            # 獲取套件名稱
            parts = md_file.parts
            if 'node_modules' in parts:
                nm_idx = parts.index('node_modules')
                if nm_idx + 1 < len(parts):
                    package_name = parts[nm_idx + 1]
                    if package_name.startswith('@') and nm_idx + 2 < len(parts):
                        package_name = f"{parts[nm_idx + 1]}/{parts[nm_idx + 2]}"
                    
                    file_name = md_file.name.upper()
                    
                    # 分類檔案
                    if 'README' in file_name:
                        categories['README'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content,
                            'size': len(content),
                            'lines': content.count('\n')
                        })
                        package_info[package_name]['readme'] = content
                    elif 'LICENSE' in file_name:
                        categories['LICENSE'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content,
                            'size': len(content)
                        })
                        package_info[package_name]['license'] = content
                    elif 'CHANGELOG' in file_name or 'HISTORY' in file_name:
                        cat = 'CHANGELOG' if 'CHANGELOG' in file_name else 'HISTORY'
                        categories[cat].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content,
                            'size': len(content)
                        })
                        package_info[package_name]['changelog'] = content
                    elif 'CONTRIBUTING' in file_name:
                        categories['CONTRIBUTING'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content
                        })
                    elif 'SECURITY' in file_name:
                        categories['SECURITY'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content
                        })
                    elif 'CODE_OF_CONDUCT' in file_name:
                        categories['CODE_OF_CONDUCT'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content
                        })
                    else:
                        categories['OTHER'].append({
                            'package': package_name,
                            'file': md_file.name,
                            'content': content,
                            'size': len(content)
                        })
                        package_info[package_name]['other_docs'].append(content)
                    
                    package_info[package_name]['name'] = package_name
                    package_info[package_name]['path'] = str(md_file.parent)
        
        except Exception as e:
            print(f"讀取 {md_file} 時出錯: {e}")
    
    return categories, package_info

def generate_consolidated_report(categories, package_info):
    """生成整合報告"""
    
    print("生成整合報告...")
    
    # 統計
    total_readmes = len(categories['README'])
    total_licenses = len(categories['LICENSE'])
    
    # 篩選重要的 README（核心套件）
    core_packages = [
        'playwright', 'playwright-core', 
        'amqplib', 
        'pino', 'pino-pretty',
        'typescript',
        '@types/node', '@types/amqplib',
        'tsx'
    ]
    
    # 按重要性分組
    core_readmes = []
    dev_tool_readmes = []
    dependency_readmes = []
    
    for item in categories['README']:
        pkg = item['package']
        if any(core in pkg for core in core_packages):
            core_readmes.append(item)
        elif pkg.startswith('@types') or 'eslint' in pkg or 'prettier' in pkg:
            dev_tool_readmes.append(item)
        else:
            dependency_readmes.append(item)
    
    print(f"核心套件 README: {len(core_readmes)}")
    print(f"開發工具 README: {len(dev_tool_readmes)}")
    print(f"依賴套件 README: {len(dependency_readmes)}")
    print()
    
    return {
        'core': core_readmes,
        'dev_tools': dev_tool_readmes,
        'dependencies': dependency_readmes,
        'licenses': categories['LICENSE'],
        'changelogs': categories['CHANGELOG'],
        'other': categories['OTHER']
    }

def main():
    print("=" * 80)
    print("整合 Node_modules MD 檔案內容")
    print("=" * 80)
    print()
    
    result = extract_md_content()
    
    if result:
        categories, package_info = result
        
        print("=" * 80)
        print("分類統計")
        print("=" * 80)
        for cat, items in categories.items():
            print(f"{cat}: {len(items)} 個檔案")
        print()
        
        # 生成報告數據
        report_data = generate_consolidated_report(categories, package_info)
        
        # 儲存為 JSON 供後續使用
        import json
        with open('_node_modules_md_content.json', 'w', encoding='utf-8') as f:
            json.dump(report_data, f, ensure_ascii=False, indent=2)
        
        print("✅ 內容已提取並儲存至: _node_modules_md_content.json")
        print()
        
        return report_data

if __name__ == '__main__':
    main()
